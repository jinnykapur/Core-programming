/*
Create a program to convert the distance of 10.8 kilometers to miles.
Hint: 1 km = 1.6 miles
I/P => NONE
O/P => The distance  ___ km in miles is ___

*/

import java.util.*;

public class q3_DistanceConvert{
	public static void main(String args[]){
		double dkm=10.8;
		double dmile=dkm*1.6;
		System.out.println("The distance "+dkm+" km in miles is "+dmile+" miles.");
		//Output: The distance 10.8 km in miles is 17.28 miles.
	}
}

