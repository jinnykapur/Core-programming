/*
Sam’s mark in Maths is 94, Physics is 95 and Chemistry is 96 out of 100. 
Find the average percent mark in PCM
I/P => NONE
O/P => Sam’s average mark in PCM is ___ 
*/

import java.util.*;

public class SamMarks{
	public static void main(String args[]){
		int p=95, c=96, m=94;
		int avg=(p+c+m)/3;
		System.out.println("Sam's average mark in PCM is "+avg+".");
		//Output: Sam's average mark in PCM is 95.
	}
}



